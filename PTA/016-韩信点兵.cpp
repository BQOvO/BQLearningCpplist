/**
 * 题目：韩信点兵
 * 来源：PTA 30
 * 难度：中等
 * 标签：数学, 枚举, 中国剩余定理
 *
 * == 原题 ==
 * 韩信有一队兵，他想知道有多少人，便让士兵排队报数。
 *   按 3 人成行排列，多 2 人；
 *   按 5 人成行排列，多 3 人；
 *   按 7 人成行排列，多 2 人；
 * 请问韩信至少有多少兵？
 * 请输入两个正整数 A 和 B（A < B），输出 A 和 B 间第一个满足条件的数，
 * 如果不存在输出 no。
 *
 * 输入格式:
 *   输入两个正整数：A B
 *
 * 输出格式:
 *   如果存在满足条件的数 C 输出：C，否则输出：no
 *
 * 样例 #1:
 *   输入: 1 100
 *   输出: 23
 *
 * 样例 #2:
 *   输入: 25 50
 *   输出: no
 */
#include <bits/stdc++.h>
using namespace std;
int main(){
    int a,b;
    int nums=0;
    scanf("%d %d",&a,&b);
    for (int i=a;i<=b;i++){
        if (i%3==2 && i%5==3 && i%7==2){
            printf("%d",i);
            nums++;
        }else{
            if(nums==1){
                break;
            }
        }
    }
    if (nums==0){
        printf("no");
    }
    return 0;
}