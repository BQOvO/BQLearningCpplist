/**
 * 题目：LX206 N进制转十进制
 * 来源：PTA LX206
 * 难度：简单
 * 标签：数学, 进制转换
 *
 * == 原题 ==
 * LX206 N进制转十进制
 * 给定一个三位的N进制数值，每个数位上的数值都符合N进制的要求，
 * 求其对应的十进制数值。
 *
 * 输入格式:
 *   一行，两个数 v 和 N，空格分隔。N 表示 N 进制，2 <= N <= 9；
 *   v 是一个三位的 N 进制数。
 *
 * 输出格式:
 *   对应的十进制。
 *
 * 输入样例:
 *   257 9
 *
 * 输出样例:
 *   214
 *
 * 提示:
 *   2*9^2 + 5*9^1 + 7*9^0 = 2*10^2 + 1*10^1 + 4*10^0
 */
#include "iostream"
#include <cstdio>
using namespace std;
int main(){
    int v,n,m,a,b,c;
    scanf("%d %d",&v,&n);
    a=v/100;
    b=(v%100)/10;
    c=(v%100)%10;
    m=a*n*n+b*n+c;
    printf("%d\n",m);
    return 0;
}